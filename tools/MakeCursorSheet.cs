// Generates the Glacier cursor preview assets from the production drawing
// code, so every preview is pixel-identical to the cursors Coldy installs.
//
// Build (after building Coldy.exe in the repo root):
//   C:\Windows\Microsoft.NET\Framework64\v4.0.30319\csc.exe /nologo /target:exe
//     /r:Coldy.exe /r:System.Drawing.dll /r:System.Windows.Forms.dll
//     /out:tools\MakeCursorSheet.exe tools\MakeCursorSheet.cs
//
// Run from the repo root:
//   tools\MakeCursorSheet.exe [outputDir]     (default: assets\cursors)
//
// Outputs:
//   png\<style>-32.png / -64.png / -128.png   transparent pointer sprites
//   png\hotspots.js                           hotspot table for preview.html
//   coldy-cursors-sheet.png                   contact sheet, 3 backgrounds

using System;
using System.Drawing;
using System.Drawing.Drawing2D;
using System.Drawing.Imaging;
using System.Drawing.Text;
using System.IO;
using System.Text;

static class MakeCursorSheet
{
    static string IdOf(string style)
    {
        switch (style)
        {
            case "arrow": return "OCR_NORMAL 32512";
            case "ibeam": return "OCR_IBEAM 32513";
            case "wait": return "OCR_WAIT 32514";
            case "cross": return "OCR_CROSS 32515";
            case "up": return "OCR_UP 32516";
            case "nwse": return "OCR_SIZENWSE 32642";
            case "nesw": return "OCR_SIZENESW 32643";
            case "we": return "OCR_SIZEWE 32644";
            case "ns": return "OCR_SIZENS 32645";
            case "move": return "OCR_SIZEALL 32646";
            case "no": return "OCR_NO 32648";
            case "hand": return "OCR_HAND 32649";
            case "busy": return "OCR_APPSTARTING 32650";
            case "help": return "OCR_HELP 32651";
        }
        return "";
    }

    static string CnOf(string style)
    {
        switch (style)
        {
            case "arrow": return "普通选择";
            case "ibeam": return "文本选择";
            case "wait": return "忙碌等待";
            case "cross": return "精确选择";
            case "up": return "候选选择";
            case "nwse": return "对角缩放 ↘";
            case "nesw": return "对角缩放 ↙";
            case "we": return "水平缩放";
            case "ns": return "垂直缩放";
            case "move": return "移动";
            case "no": return "不可用";
            case "hand": return "链接选择";
            case "busy": return "后台运行";
            case "help": return "帮助选择";
        }
        return "";
    }

    static int Main(string[] args)
    {
        string root = args.Length > 0 ? args[0] : Path.Combine("assets", "cursors");
        string pngDir = Path.Combine(root, "png");
        Directory.CreateDirectory(pngDir);

        int[] exportSizes = { 32, 64, 128 };
        var js = new StringBuilder();
        js.Append("// Generated by tools/MakeCursorSheet.cs - hotspots at 32 px.\r\n");
        js.Append("var COLDY_HOTSPOTS = {\r\n");
        foreach (string style in CursorFactory.AllStyles)
        {
            int hx32 = 0, hy32 = 0;
            foreach (int size in exportSizes)
            {
                int hx, hy;
                using (var bmp = CursorFactory.Render(style, size, out hx, out hy))
                {
                    bmp.Save(Path.Combine(pngDir, style + "-" + size + ".png"), ImageFormat.Png);
                    if (size == 32) { hx32 = hx; hy32 = hy; }
                }
            }
            js.AppendFormat("  \"{0}\": {{ hx: {1}, hy: {2} }},\r\n", style, hx32, hy32);
        }
        js.Append("};\r\n");

        // ---- pixel scheme: first animation frames -------------------------
        int[] pixelSizes = { 16, 32, 64, 128 };
        js.Append("var COLDY_PIXEL_HOTSPOTS = {\r\n");
        foreach (string style in CursorFactory.AllStyles)
        {
            int phx = 0, phy = 0;
            foreach (int size in pixelSizes)
            {
                int hx, hy;
                using (var bmp = CursorFactory.RenderPixelFirst(style, size, out hx, out hy))
                {
                    if (bmp == null) continue;
                    bmp.Save(Path.Combine(pngDir, "pixel-" + style + "-" + size + ".png"), ImageFormat.Png);
                    if (size == 32) { phx = hx; phy = hy; }
                }
            }
            js.AppendFormat("  \"{0}\": {{ hx: {1}, hy: {2} }},\r\n", style, phx, phy);
        }
        js.Append("};\r\n");

        // ---- felt scheme: first micro-motion frames -----------------------
        js.Append("var COLDY_FELT_HOTSPOTS = {\r\n");
        foreach (string style in CursorFactory.AllStyles)
        {
            int fhx = 0, fhy = 0;
            foreach (int size in exportSizes)
            {
                int hx, hy;
                using (var bmp = CursorFactory.RenderFelt(style, size, 0, out hx, out hy))
                {
                    bmp.Save(Path.Combine(pngDir, "felt-" + style + "-" + size + ".png"), ImageFormat.Png);
                    if (size == 32) { fhx = hx; fhy = hy; }
                }
            }
            js.AppendFormat("  \"{0}\": {{ hx: {1}, hy: {2} }},\r\n", style, fhx, fhy);
        }
        js.Append("};\r\n");
        File.WriteAllText(Path.Combine(pngDir, "hotspots.js"), js.ToString(), Encoding.UTF8);

        // ---- contact sheet ------------------------------------------------
        int[] sizes = { 16, 32, 64 };
        Color[] backs = {
            Color.FromArgb(247, 250, 253),
            Color.FromArgb(30, 36, 48),
            Color.FromArgb(62, 121, 192)
        };
        string[] backNames = { "浅色背景", "深色背景", "冰蓝背景" };
        int cell = 92, labelW = 172, headerH = 122, footerH = 116, pad = 24;
        int cols = sizes.Length * backs.Length;
        int rows = CursorFactory.AllStyles.Length;
        int W = labelW + cols * cell + pad;
        int H = headerH + rows * cell + footerH;

        Color ink = Color.FromArgb(31, 40, 56);
        Color dim = Color.FromArgb(112, 124, 142);
        using (var sheet = new Bitmap(W, H, PixelFormat.Format32bppArgb))
        using (var g = Graphics.FromImage(sheet))
        using (var fTitle = new Font("Segoe UI", 21f, FontStyle.Bold))
        using (var fSub = new Font("Microsoft YaHei", 9.5f))
        using (var fStyle = new Font("Segoe UI", 10.5f, FontStyle.Bold))
        using (var fCn = new Font("Microsoft YaHei", 9f))
        using (var fId = new Font("Consolas", 8f))
        using (var fHead = new Font("Microsoft YaHei", 9f, FontStyle.Bold))
        using (var fChip = new Font("Consolas", 8.5f))
        using (var bInk = new SolidBrush(ink))
        using (var bDim = new SolidBrush(dim))
        {
            g.SmoothingMode = SmoothingMode.AntiAlias;
            g.TextRenderingHint = TextRenderingHint.AntiAliasGridFit;
            g.Clear(Color.FromArgb(247, 250, 253));

            g.DrawString("COLDY · ICE CURSORS", fTitle, bInk, pad, 18);
            g.DrawString("Ice 光标系统 · 14 种状态 · 16 / 32 / 64 px · 由 CursorFactory.Render 生产代码直接渲染",
                fSub, bDim, pad + 2, 62);

            for (int b = 0; b < backs.Length; b++)
            {
                float x = labelW + b * sizes.Length * cell;
                using (var bb = new SolidBrush(backs[b]))
                    g.FillRectangle(bb, x, headerH - 30, sizes.Length * cell, 26);
                using (var tb = new SolidBrush(b == 0 ? ink : Color.White))
                    g.DrawString(backNames[b] + "  ·  16 / 32 / 64", fHead, tb, x + 10, headerH - 25);
            }

            for (int r = 0; r < rows; r++)
            {
                string style = CursorFactory.AllStyles[r];
                float y = headerH + r * cell;
                using (var lb = new SolidBrush(r % 2 == 0 ? Color.FromArgb(238, 244, 250) : Color.FromArgb(247, 250, 253)))
                    g.FillRectangle(lb, 0, y, labelW, cell);
                g.DrawString(style, fStyle, bInk, 18, y + 16);
                g.DrawString(CnOf(style), fCn, bDim, 18, y + 38);
                g.DrawString(IdOf(style), fId, bDim, 18, y + 60);

                for (int b = 0; b < backs.Length; b++)
                {
                    for (int c = 0; c < sizes.Length; c++)
                    {
                        float x = labelW + (b * sizes.Length + c) * cell;
                        using (var bb = new SolidBrush(backs[b]))
                            g.FillRectangle(bb, x, y, cell, cell);
                        int size = sizes[c];
                        int hx, hy;
                        using (var cur = CursorFactory.Render(style, size, out hx, out hy))
                            g.DrawImage(cur, x + (cell - size) / 2f, y + (cell - size) / 2f, size, size);
                    }
                }
                using (var line = new Pen(Color.FromArgb(28, 31, 40, 56)))
                    g.DrawLine(line, 0, y + cell, W, y + cell);
            }

            // footer: design tokens
            float fy = headerH + rows * cell + 22;
            g.DrawString("DESIGN TOKENS", fStyle, bInk, pad, fy);
            Color[] chips = {
                Color.FromArgb(248, 254, 255), Color.FromArgb(216, 243, 255),
                Color.FromArgb(158, 220, 245), Color.FromArgb(31, 40, 56),
                Color.FromArgb(226, 87, 75), Color.FromArgb(197, 236, 255),
                Color.White
            };
            string[] chipNames = { "F8FEFF", "D8F3FF", "9EDCF5", "1F2838", "E2574B", "C5ECFF", "FFFFFF" };
            float cx = pad;
            for (int i = 0; i < chips.Length; i++)
            {
                using (var cb = new SolidBrush(chips[i]))
                    g.FillRectangle(cb, cx, fy + 28, 34, 22);
                using (var edge = new Pen(Color.FromArgb(60, 31, 40, 56)))
                    g.DrawRectangle(edge, cx, fy + 28, 34, 22);
                g.DrawString(chipNames[i], fChip, bDim, cx, fy + 54);
                cx += 108;
            }
            g.DrawString("白色光晕 + 墨色描边 + 冰蓝渐变 · 圆角圆帽 · 32 单位网格 · 热点与箭头尖端逐像素对齐",
                fSub, bDim, pad, fy + 78);

            sheet.Save(Path.Combine(root, "coldy-cursors-sheet.png"), ImageFormat.Png);
        }

        // ---- pixel contact sheet ------------------------------------------
        int[] disp = { 48, 64, 64 };
        using (var sheet = new Bitmap(W, H, PixelFormat.Format32bppArgb))
        using (var g = Graphics.FromImage(sheet))
        using (var fTitle = new Font("Segoe UI", 21f, FontStyle.Bold))
        using (var fSub = new Font("Microsoft YaHei", 9.5f))
        using (var fStyle = new Font("Segoe UI", 10.5f, FontStyle.Bold))
        using (var fCn = new Font("Microsoft YaHei", 9f))
        using (var fId = new Font("Consolas", 8f))
        using (var fHead = new Font("Microsoft YaHei", 9f, FontStyle.Bold))
        using (var bInk = new SolidBrush(ink))
        using (var bDim = new SolidBrush(dim))
        {
            g.SmoothingMode = SmoothingMode.AntiAlias;
            g.InterpolationMode = InterpolationMode.NearestNeighbor;
            g.PixelOffsetMode = PixelOffsetMode.Half;
            g.TextRenderingHint = TextRenderingHint.AntiAliasGridFit;
            g.Clear(Color.FromArgb(247, 250, 253));

            g.DrawString("COLDY · PIXEL CURSORS", fTitle, bInk, pad, 18);
            g.DrawString("像素光标方案 · 作者 线框xiankuang · 16×16 · 11 帧 @ 12fps · 预览为动画首帧（软件内为完整动画）",
                fSub, bDim, pad + 2, 62);

            for (int b = 0; b < backs.Length; b++)
            {
                float x = labelW + b * sizes.Length * cell;
                using (var bb = new SolidBrush(backs[b]))
                    g.FillRectangle(bb, x, headerH - 30, sizes.Length * cell, 26);
                using (var tb = new SolidBrush(b == 0 ? ink : Color.White))
                    g.DrawString(backNames[b] + "  ·  16 / 32 / 64", fHead, tb, x + 10, headerH - 25);
            }

            for (int r = 0; r < rows; r++)
            {
                string style = CursorFactory.AllStyles[r];
                float y = headerH + r * cell;
                using (var lb = new SolidBrush(r % 2 == 0 ? Color.FromArgb(238, 244, 250) : Color.FromArgb(247, 250, 253)))
                    g.FillRectangle(lb, 0, y, labelW, cell);
                g.DrawString(style, fStyle, bInk, 18, y + 16);
                g.DrawString(CnOf(style), fCn, bDim, 18, y + 38);
                g.DrawString(IdOf(style), fId, bDim, 18, y + 60);

                for (int b = 0; b < backs.Length; b++)
                {
                    for (int c = 0; c < sizes.Length; c++)
                    {
                        float x = labelW + (b * sizes.Length + c) * cell;
                        using (var bb = new SolidBrush(backs[b]))
                            g.FillRectangle(bb, x, y, cell, cell);
                        int hx, hy;
                        using (var cur = CursorFactory.RenderPixelFirst(style, sizes[c], out hx, out hy))
                        {
                            if (cur == null) continue;
                            int d = disp[c];
                            g.DrawImage(cur, x + (cell - d) / 2f, y + (cell - d) / 2f, d, d);
                        }
                    }
                }
                using (var line = new Pen(Color.FromArgb(28, 31, 40, 56)))
                    g.DrawLine(line, 0, y + cell, W, y + cell);
            }

            float fy = headerH + rows * cell + 22;
            g.DrawString("CREDIT & NOTES", fStyle, bInk, pad, fy);
            g.DrawString("动态像素光标 · 作者：线框xiankuang · bilibili space.bilibili.com/400839602 · 更多光标 xk-downloads.ovso.top",
                fSub, bDim, pad, fy + 28);
            g.DrawString("由简易光标制作器制作 · 经作者 installer 内嵌 ZIP 提取（tools/extract_pixel_pack.py）· 最近邻缩放保持像素网格",
                fSub, bDim, pad, fy + 50);
            g.DrawString("install.inf 另含 Handwriting / Person / Pin；Person(32652) / Pin(32653) 已纳入，Handwriting 无系统光标 ID 故不安装",
                fSub, bDim, pad, fy + 72);

            sheet.Save(Path.Combine(root, "coldy-pixel-sheet.png"), ImageFormat.Png);
        }

        // ---- felt & frost contact sheet -----------------------------------
        using (var sheet = new Bitmap(W, H, PixelFormat.Format32bppArgb))
        using (var g = Graphics.FromImage(sheet))
        using (var fTitle = new Font("Segoe UI", 21f, FontStyle.Bold))
        using (var fSub = new Font("Microsoft YaHei", 9.5f))
        using (var fStyle = new Font("Segoe UI", 10.5f, FontStyle.Bold))
        using (var fCn = new Font("Microsoft YaHei", 9f))
        using (var fId = new Font("Consolas", 8f))
        using (var fHead = new Font("Microsoft YaHei", 9f, FontStyle.Bold))
        using (var fChip = new Font("Consolas", 8.5f))
        using (var bInk = new SolidBrush(ink))
        using (var bDim = new SolidBrush(dim))
        {
            g.SmoothingMode = SmoothingMode.AntiAlias;
            g.TextRenderingHint = TextRenderingHint.AntiAliasGridFit;
            g.Clear(Color.FromArgb(247, 250, 253));

            g.DrawString("COLDY · FROST'S DESCENT CURSORS", fTitle, bInk, pad, 18);
            g.DrawString("Frost's Descent（霜降）光标系统 · 14 态形状/纹样 · 针织/毛毡/镀铬/冰晶/彩虹线缆 · 由 CursorFactory.RenderFelt 生产代码渲染（预览为微动效首帧）",
                fSub, bDim, pad + 2, 62);

            for (int b = 0; b < backs.Length; b++)
            {
                float x = labelW + b * sizes.Length * cell;
                using (var bb = new SolidBrush(backs[b]))
                    g.FillRectangle(bb, x, headerH - 30, sizes.Length * cell, 26);
                using (var tb = new SolidBrush(b == 0 ? ink : Color.White))
                    g.DrawString(backNames[b] + "  ·  16 / 32 / 64", fHead, tb, x + 10, headerH - 25);
            }

            for (int r = 0; r < rows; r++)
            {
                string style = CursorFactory.AllStyles[r];
                float y = headerH + r * cell;
                using (var lb = new SolidBrush(r % 2 == 0 ? Color.FromArgb(238, 244, 250) : Color.FromArgb(247, 250, 253)))
                    g.FillRectangle(lb, 0, y, labelW, cell);
                g.DrawString(style, fStyle, bInk, 18, y + 16);
                g.DrawString(CnOf(style), fCn, bDim, 18, y + 38);
                g.DrawString(IdOf(style), fId, bDim, 18, y + 60);

                for (int b = 0; b < backs.Length; b++)
                {
                    for (int c = 0; c < sizes.Length; c++)
                    {
                        float x = labelW + (b * sizes.Length + c) * cell;
                        using (var bb = new SolidBrush(backs[b]))
                            g.FillRectangle(bb, x, y, cell, cell);
                        int size = sizes[c];
                        int hx, hy;
                        using (var cur = CursorFactory.RenderFelt(style, size, 0, out hx, out hy))
                            g.DrawImage(cur, x + (cell - size) / 2f, y + (cell - size) / 2f, size, size);
                    }
                }
                using (var line = new Pen(Color.FromArgb(28, 31, 40, 56)))
                    g.DrawLine(line, 0, y + cell, W, y + cell);
            }

            float fy = headerH + rows * cell + 22;
            g.DrawString("DESIGN TOKENS · FROST'S DESCENT", fStyle, bInk, pad, fy);
            Color[] chips = {
                Color.FromArgb(245, 247, 248), Color.FromArgb(91, 135, 166),
                Color.FromArgb(157, 184, 154), Color.FromArgb(226, 87, 75),
                Color.FromArgb(239, 231, 216), Color.FromArgb(53, 198, 244),
                Color.FromArgb(140, 152, 162), Color.FromArgb(31, 40, 56)
            };
            string[] chipNames = { "F5F7F8", "5B87A6", "9DB89A", "E2574B", "EFE7D8", "35C6F4", "8C98A2", "1F2838" };
            float cx = pad;
            for (int i = 0; i < chips.Length; i++)
            {
                using (var cb = new SolidBrush(chips[i]))
                    g.FillRectangle(cb, cx, fy + 28, 34, 22);
                using (var edge = new Pen(Color.FromArgb(60, 31, 40, 56)))
                    g.DrawRectangle(edge, cx, fy + 28, 34, 22);
                g.DrawString(chipNames[i], fChip, bDim, cx, fy + 54);
                cx += 100;
            }
            g.DrawString("母题即功能：针织拉伸=缩放 · 镀铬勺=帮助 · 雪球=移动 · 围巾结=禁止 · 冰晶=等待 · 青点=品牌签名 · 无人物无脸",
                fSub, bDim, pad, fy + 78);

            sheet.Save(Path.Combine(root, "coldy-felt-sheet.png"), ImageFormat.Png);
        }

        Console.WriteLine("Wrote " + Path.GetFullPath(root));
        return 0;
    }
}